/**
 * Generate the API types from the backend's schemas (the contract's machine-readable form):
 * `docs/schema/openapi.json` → `src/api/generated/openapi.ts` (openapi-typescript) and
 * `docs/schema/answer.schema.json` → `src/api/generated/answer.ts` (json-schema-to-typescript).
 * `src/api/types.ts` re-exports them under the names the app uses.
 *
 * Usage: `node scripts/gen-types.ts` (write) · `node scripts/gen-types.ts --check` (fail on drift, for CI)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";

/** Repo-relative inputs and outputs. */
const root = (path: string) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const OPENAPI_IN = root("../docs/schema/openapi.json");
const ANSWER_IN = root("../docs/schema/answer.schema.json");
const OPENAPI_OUT = root("src/api/generated/openapi.ts");
const ANSWER_OUT = root("src/api/generated/answer.ts");

/** Header on every generated file. */
const BANNER =
  "/* eslint-disable */\n// Generated by scripts/gen-types.ts from docs/schema/. Do not edit: run `npm run gen:types`.\n\n";

/**
 * Render both generated files.
 *
 * @returns Output path → file content.
 */
async function render(): Promise<Map<string, string>> {
  const openapi = astToString(await openapiTS(JSON.parse(readFileSync(OPENAPI_IN, "utf8")) as OpenAPI3));
  const answerSchema = JSON.parse(readFileSync(ANSWER_IN, "utf8")) as Parameters<typeof compile>[0];
  const answer = await compile(answerSchema, "Answer", {
    bannerComment: "",
    additionalProperties: false,
    ignoreMinAndMaxItems: true,
  });
  return new Map([
    [OPENAPI_OUT, BANNER + openapi],
    [ANSWER_OUT, BANNER + answer],
  ]);
}

const check = process.argv.includes("--check");
const drifted: string[] = [];
for (const [path, content] of await render()) {
  if (!check) {
    writeFileSync(path, content);
    continue;
  }
  if (!existsSync(path) || readFileSync(path, "utf8") !== content) drifted.push(path);
}
if (drifted.length > 0) {
  console.error(`Generated types are out of date (run npm run gen:types):\n${drifted.join("\n")}`);
  process.exit(1);
}
console.info(check ? "Generated API types are up to date." : "Wrote src/api/generated/{openapi,answer}.ts.");
